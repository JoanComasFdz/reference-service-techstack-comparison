    [Fact]
    public async Task GenerateReportAsync_ShouldDifferentiateBetweenProcessAndContainerMetrics()
    {
        // Arrange
        var outputDirectory = System.FileSystem.CreateTempDirectory("report-test");
        var testReport = new TestReportBuilder()
            .WithSystemInfo(SystemInfoBuilder.CreateIntelI9())
            .Build();

        try
        {
            // Act
            await System.Reporting.ReportGenerator.GenerateReportAsync(outputDirectory, testReport);

            // Assert - Process metrics use "memory_rss_mb" and include "threads"
            var resourceMetricsPath = Directory.GetFiles(outputDirectory, "*.resource-metrics.json").First();
            var json = await File.ReadAllTextAsync(resourceMetricsPath);
            var doc = JsonDocument.Parse(json);
            var samples = doc.RootElement.GetProperty("samples");

            if (samples.GetArrayLength() > 0)
            {
                var firstSample = samples[0];
                Assert.True(firstSample.TryGetProperty("memory_rss_mb", out _));
                Assert.True(firstSample.TryGetProperty("threads", out _));
                Assert.False(firstSample.TryGetProperty("memory_mb", out _));
            }

            // Assert - Container metrics use "memory_mb" and NO threads
            var rabbitmqMetricsPath = Directory.GetFiles(outputDirectory, "*.rabbitmq-metrics.json").First();
            json = await File.ReadAllTextAsync(rabbitmqMetricsPath);
            doc = JsonDocument.Parse(json);
            samples = doc.RootElement.GetProperty("samples");

            if (samples.GetArrayLength() > 0)
            {
                var firstSample = samples[0];
                Assert.True(firstSample.TryGetProperty("memory_mb", out _));
                Assert.False(firstSample.TryGetProperty("threads", out _));
                Assert.False(firstSample.TryGetProperty("memory_rss_mb", out _));
            }
        }
        finally
        {
            System.FileSystem.CleanupTempDirectory(outputDirectory);
        }
    }

