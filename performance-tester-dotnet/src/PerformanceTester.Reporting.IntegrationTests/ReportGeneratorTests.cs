    [Fact]
    public async Task GenerateReportAsync_ShouldUseCorrectDecimalPrecision()
    {
        // Arrange
        var outputDirectory = System.FileSystem.CreateTempDirectory("report-test");
        
        // Create test report with specific decimal precision values
        var phaseTimestamps = new PhaseTimestamps
        {
            Phase1Start = 0.0,
            Phase1End = 5.333,
            Phase2Start = 5.333,
            Phase2End = 44.556,
            Phase3Start = 45.000,
            Phase3End = 75.333
        };

        var results = new TestResults
        {
            Phase1Publish = new PublishResults
            {
                DurationSeconds = 5.333,
                ThroughputEventsPerSec = 1875.22  // 2 decimals
            },
            Phase2Consume = new ConsumeResults
            {
                DurationSeconds = 39.223,
                ThroughputEventsPerSec = 254.98
            },
            Phase3Api = new ApiResults
            {
                DurationSeconds = 30.333,
                TotalRequests = 3245,
                ThroughputCallsPerSec = 107.00,
                SuccessCount = 3245,
                SuccessPercentage = 100.0,  // 1 decimal
                ErrorCount = 0,
                ErrorPercentage = 0.0
            }
        };

        var testReport = new TestReportBuilder()
            .WithRuntime(125.456)  // 3 decimals
            .WithPhaseTimestamps(phaseTimestamps)
            .WithResults(results)
            .WithSystemInfo(SystemInfoBuilder.CreateIntelI9())
            .Build();

        try
        {
            // Act
            await System.Reporting.ReportGenerator.GenerateReportAsync(outputDirectory, testReport);

            // Assert - Read main report
            var mainReportPath = Directory.GetFiles(outputDirectory, "*testservice.json").First();
            var json = await File.ReadAllTextAsync(mainReportPath);
            var doc = JsonDocument.Parse(json);
            var root = doc.RootElement;

            // Time in seconds: 3 decimals
            var totalRuntime = root.GetProperty("total_runtime_seconds").GetDouble();
            Assert.Equal(125.456, totalRuntime);

            // Throughput (per sec): 2 decimals
            var publishThroughput = root.GetProperty("results")
                .GetProperty("phase1_publish")
                .GetProperty("throughput_events_per_sec")
                .GetDouble();
            Assert.Equal(1875.22, publishThroughput);

            // Percentage: 1 decimal
            var successPercentage = root.GetProperty("results")
                .GetProperty("phase3_api")
                .GetProperty("success_percentage")
                .GetDouble();
            Assert.Equal(100.0, successPercentage);
        }
        finally
        {
            System.FileSystem.CleanupTempDirectory(outputDirectory);
        }
    }

